-- 4. 配额预扣流水（每条调用一条；成功/中断=已结算，失败=已回滚；
--    预扣量 = 实际 Token × 1.15 的估算口径）
-- ------------------------------------------------------------------------------
INSERT INTO t_quota_reservation
    (trace_id, user_id, est_tokens, status, actual_tokens, settled_time, rollback_time, gmt_create)
SELECT l.trace_id,
       l.user_id,
       CASE WHEN l.success = 1 OR l.interrupted = 1
            THEN CEIL((l.prompt_tokens + l.completion_tokens) * 1.15)
            ELSE l.prompt_tokens + 800 END,
       CASE WHEN l.success = 1 OR l.interrupted = 1 THEN 1 ELSE 2 END,
       CASE WHEN l.success = 1 OR l.interrupted = 1 THEN l.total_tokens ELSE NULL END,
       CASE WHEN l.success = 1 OR l.interrupted = 1
            THEN l.gmt_create + INTERVAL (l.latency_ms DIV 1000) SECOND ELSE NULL END,
       CASE WHEN l.success = 0 AND l.interrupted = 0
            THEN l.gmt_create + INTERVAL (l.latency_ms DIV 1000) SECOND ELSE NULL END,
       l.gmt_create
FROM t_invoke_log_v2 l
WHERE l.trace_id LIKE 'demo-%';

-- ------------------------------------------------------------------------------
-- 5. 计费日汇总（按 日期 × 用户 × 模型 聚合已结算调用；失败调用不计费；
--    看板 weeklyTrend / 模型分布读取本表与窄表，口径一致）
--    ⚠ 第 0 节整段删除了窗口内的日汇总（含窗口内真实流量的行），
--    故本节按窗口内全量日志（真实 + 演示）重建，恢复不变量：
--    billing_daily[窗口] = 窄表已结算日志按（日×用户×模型）聚合。
-- ------------------------------------------------------------------------------
INSERT INTO t_billing_daily
    (user_id, stat_date, model_code, call_count,
     total_prompt_tokens, total_completion_tokens, total_tokens, total_cost)
SELECT user_id,
       DATE(gmt_create),
       model_code,
       COUNT(*),
       SUM(prompt_tokens),
       SUM(completion_tokens),
       SUM(total_tokens),
       SUM(cost_amount)
FROM t_invoke_log_v2
WHERE DATE(gmt_create) BETWEEN '2026-10-27' AND '2026-11-02'
  AND (success = 1 OR interrupted = 1)
GROUP BY user_id, DATE(gmt_create), model_code;

-- ------------------------------------------------------------------------------
-- 6. 用户用量水位同步（口径：已结算 = success=1 或 interrupted=1；
--    used_daily=当日、used_monthly=当月，与真实流量合并重算，幂等）
-- ------------------------------------------------------------------------------
UPDATE t_user u
SET used_daily   = COALESCE((SELECT SUM(l.total_tokens)
                               FROM t_invoke_log_v2 l
                              WHERE l.user_id = u.id
                                AND (l.success = 1 OR l.interrupted = 1)
                                AND l.gmt_create >= CURDATE()), 0),
    used_monthly = COALESCE((SELECT SUM(l.total_tokens)
                               FROM t_invoke_log_v2 l
                              WHERE l.user_id = u.id
                                AND (l.success = 1 OR l.interrupted = 1)
                                AND l.gmt_create >= DATE_FORMAT(CURDATE(), '%Y-%m-01')), 0);

